import { readFileSync, writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';

const [input = '../schemas/openapi.json', output = 'src/api/schema.gen.ts'] = process.argv.slice(2);
const spec = JSON.parse(readFileSync(input, 'utf8'));

const ids = new Set();
for (const item of Object.values(spec.paths ?? {})) {
  for (const op of Object.values(item)) {
    if (!op || typeof op !== 'object' || typeof op.operationId !== 'string') continue;
    if (ids.has(op.operationId)) throw new Error(`duplicate operationId ${op.operationId} in ${input}`);
    ids.add(op.operationId);
  }
}

const ast = await openapiTS(spec, { defaultNonNullable: false });
const header = '/**\n * This file was auto-generated by openapi-typescript from schemas/openapi.json (npm run gen:api).\n * Do not make direct changes to the file.\n */\n\n';
writeFileSync(output, header + astToString(ast));
console.log(`${input} -> ${output}`);
