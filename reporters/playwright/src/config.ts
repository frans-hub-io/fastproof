import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { resolve } from 'node:path';

import { detectCi } from './ci';
import { DEFAULT_SECRET_ENV, type MaskOptions } from './mask';
import type { LaunchStart } from './types';

/** Reporter options (the second element of the `reporter` tuple in `playwright.config`). */
export interface FastProofOptions {
  /** Server URL (`FASTPROOF_URL`). Without it the reporter is off. */
  url?: string;
  /** API token (`FASTPROOF_TOKEN` or a file in `FASTPROOF_TOKEN_FILE`). */
  token?: string;
  /** Project key (`FASTPROOF_PROJECT`). */
  project?: string;
  /** Launch external id (`FASTPROOF_LAUNCH`); shards with the same id join one launch. Default: from CI. */
  launch?: string;
  /** Launch name (`FASTPROOF_LAUNCH_NAME`). */
  launchName?: string;
  /** Environment key, part of test identity (`FASTPROOF_ENVIRONMENT`). */
  environment?: string;
  /** Launch attributes. */
  attributes?: Record<string, string>;
  /** Mark the launch as a debug run. */
  debug?: boolean;
  /** `false` (or `FASTPROOF_ENABLED=false`) turns the reporter off. */
  enabled?: boolean;
  /** Write everything to the spool and send nothing (`FASTPROOF_OFFLINE=true`). */
  offline?: boolean;
  /** Spool directory (`FASTPROOF_SPOOL_DIR`, default `.fastproof/spool`). */
  spoolDir?: string;
  /** Spool size limit in bytes (default 200 MB). */
  spoolMaxBytes?: number;
  /** How long `onEnd` waits for the last uploads (default 30 s). */
  flushTimeoutMs?: number;
  /** Per-request timeout (default 15 s). */
  requestTimeoutMs?: number;
  /** Batch interval of the background sender (default 200 ms). */
  batchIntervalMs?: number;
  /** Open results as `running` when a test begins (default true). */
  runningResults?: boolean;
  /** Stream stdout, stderr and steps live (default true). */
  liveLogs?: boolean;
  /** Finish the launch at the end: `auto` finishes only launches this run created with its own id. */
  finishLaunch?: 'auto' | 'always' | 'never';
  /** Secret masking; `env` names add to the defaults `*TOKEN*`, `*SECRET*`, `*PASSWORD*`, `*_KEY` and similar. */
  secrets?: MaskOptions;
  /** Upload attachments (screenshots, video, traces, files from `testInfo.attach`); default true. */
  attachments?: boolean;
  /** Largest attachment uploaded, in bytes (default 512 MB). */
  maxAttachmentBytes?: number;
  /** Print the hint about sending the spool later (default true). */
  uploadHint?: boolean;
  /** No messages except warnings. */
  quiet?: boolean;
}

export interface Config {
  enabled: boolean;
  reason?: string;
  url: string;
  token: string;
  project: string;
  offline: boolean;
  launch: LaunchStart;
  /** The external id was generated by this run (no CI, no option). */
  ownLaunch: boolean;
  spoolDir: string;
  spoolMaxBytes: number;
  flushTimeoutMs: number;
  requestTimeoutMs: number;
  batchIntervalMs: number;
  runningResults: boolean;
  liveLogs: boolean;
  finishLaunch: 'auto' | 'always' | 'never';
  secrets: MaskOptions;
  /** Environment whose secret-looking variables are masked. */
  env: Env;
  attachments: boolean;
  maxAttachmentBytes: number;
  uploadHint: boolean;
  quiet: boolean;
}

type Env = Record<string, string | undefined>;

function flag(v: string | undefined): boolean | undefined {
  if (v === undefined || v.trim() === '') return undefined;
  return !['0', 'false', 'no', 'off'].includes(v.trim().toLowerCase());
}

function list(v: string | undefined): string[] | undefined {
  if (!v || !v.trim()) return undefined;
  return v
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);
}

const PROJECT_KEY = /^[a-z0-9][a-z0-9-]{1,62}$/;

export function resolveConfig(o: FastProofOptions = {}, env: Env = process.env, cwd = process.cwd()): Config {
  let token = o.token ?? env.FASTPROOF_TOKEN ?? '';
  if (!token && env.FASTPROOF_TOKEN_FILE) {
    try {
      token = readFileSync(env.FASTPROOF_TOKEN_FILE, 'utf8').trim();
    } catch {
      token = '';
    }
  }
  const url = (o.url ?? env.FASTPROOF_URL ?? '').trim();
  const project = (o.project ?? env.FASTPROOF_PROJECT ?? '').trim();
  const ci = detectCi(env);
  const explicit = o.launch ?? env.FASTPROOF_LAUNCH;
  const externalId = explicit?.trim() || ci?.externalId || `local-${randomUUID()}`;
  const name =
    o.launchName ??
    env.FASTPROOF_LAUNCH_NAME ??
    ci?.name ??
    (explicit?.trim() || `${project || 'tests'} ${new Date().toISOString().slice(0, 16).replace('T', ' ')}`);
  const launch: LaunchStart = { externalId, name };
  const attrs = Object.entries(o.attributes ?? {}).map(([key, value]) => ({ key, value: String(value) }));
  if (attrs.length) launch.attributes = attrs;
  if (ci && Object.keys(ci.ci).length) launch.ci = ci.ci;
  if (ci && Object.keys(ci.vcs).length) launch.vcs = ci.vcs;
  const environment = o.environment ?? env.FASTPROOF_ENVIRONMENT;
  if (environment?.trim()) launch.environment = { key: environment.trim(), values: {} };
  if (o.debug) launch.debug = true;

  const secretsEnv = list(env.FASTPROOF_SECRET_ENV);
  const secretPatterns = list(env.FASTPROOF_SECRET_PATTERNS);
  const secrets: MaskOptions = {
    ...o.secrets,
    env: [...DEFAULT_SECRET_ENV, ...(o.secrets?.env ?? []), ...(secretsEnv ?? [])],
  };
  if (secretPatterns) secrets.patterns = [...(o.secrets?.patterns ?? []), ...secretPatterns];
  if (token) secrets.values = [...(secrets.values ?? []), token];

  let enabled = (o.enabled ?? flag(env.FASTPROOF_ENABLED) ?? true) !== false;
  let reason: string | undefined;
  const offline = o.offline ?? flag(env.FASTPROOF_OFFLINE) ?? false;
  if (!enabled) reason = 'disabled';
  else if (!url && !offline) {
    enabled = false;
    reason = 'FASTPROOF_URL is not set';
  } else if (!PROJECT_KEY.test(project)) {
    enabled = false;
    reason = 'FASTPROOF_PROJECT is missing or not a valid project key';
  }
  const num = (v: number | undefined, e: string | undefined, d: number) => {
    const n = v ?? (e !== undefined && e.trim() !== '' ? Number(e) : undefined);
    return n !== undefined && Number.isFinite(n) && n >= 0 ? n : d;
  };
  const cfg: Config = {
    enabled,
    url,
    token,
    project,
    offline,
    launch,
    ownLaunch: !explicit?.trim() && !ci?.externalId,
    spoolDir: resolve(cwd, o.spoolDir ?? env.FASTPROOF_SPOOL_DIR ?? '.fastproof/spool'),
    spoolMaxBytes: num(o.spoolMaxBytes, env.FASTPROOF_SPOOL_MAX_BYTES, 200 * 1024 * 1024),
    flushTimeoutMs: num(o.flushTimeoutMs, env.FASTPROOF_FLUSH_TIMEOUT_MS, 30_000),
    requestTimeoutMs: num(o.requestTimeoutMs, undefined, 15_000),
    batchIntervalMs: Math.max(20, num(o.batchIntervalMs, undefined, 200)),
    runningResults: o.runningResults ?? true,
    liveLogs: o.liveLogs ?? flag(env.FASTPROOF_LIVE_LOGS) ?? true,
    finishLaunch: o.finishLaunch ?? 'auto',
    secrets,
    env,
    attachments: o.attachments ?? true,
    maxAttachmentBytes: num(o.maxAttachmentBytes, undefined, 512 * 1024 * 1024),
    uploadHint: o.uploadHint ?? true,
    quiet: o.quiet ?? flag(env.FASTPROOF_QUIET) ?? false,
  };
  if (reason) cfg.reason = reason;
  return cfg;
}
